/* ============================================================================
 * control.h  ——  控制逻辑模块（头文件）
 * ----------------------------------------------------------------------------
 * 职责划分（正好对应考核要求的两个任务）：
 *
 *   ┌─ remoteTask（优先级 AboveNormal）──────────────────────┐
 *   │   Control_RemoteUpdate()   每 10 ms                   │
 *   │     读遥控 → 判档位(SWA5) → 算摇杆目标                │
 *   └───────────────────────────────────────────────────────┘
 *                          ↓ 存到全局变量（32 位，读写原子）
 *   ┌─ controlTask（优先级 High）───────────────────────────┐
 *   │   Control_Update()         每 1 ms                    │
 *   │     保护检查 → 位置环 → 速度环 → 发 CAN               │
 *   └───────────────────────────────────────────────────────┘
 *
 * 考核要求：
 *   SWA5 上拨 → 位置模式（左摇杆 → ±90°，角度环+速度环串级）
 *   SWA5 下拨 → 速度模式（右摇杆 → ±½额定转速，速度环）
 *   中间      → 停机
 * ==========================================================================*/

#ifndef CONTROL_H
#define CONTROL_H

#include <stdint.h>
#include "remote.h"      /* SBUS_CH5_SWA 等通道定义 */


/* ============================================================================
 * 一、可调参数
 * ==========================================================================*/

/* ---- 两个任务的周期 ---- */
#define CONTROL_DT_S            0.001f      /* controlTask：1 kHz */
#define CTRL_REMOTE_DT_S        0.010f      /* remoteTask ：100 Hz */

/* ---- 哪个通道干什么（⚠️ 遥控器里映射可改，上机时推一下确认）---- */
#define CTRL_CH_POS_STICK       SBUS_CH3_LEFT_UD     /* 位置模式：左摇杆 上下 */
#define CTRL_CH_SPEED_STICK     SBUS_CH2_RIGHT_UD    /* 速度模式：右摇杆 上下 */

/* ---- SWA 三位开关的判档阈值 ----
 * ⚠️ 实测值（HT-10A 遥控器）：上拨 = 192，中间 = 992，下拨 = 1792
 *    ⭐ 上拨是【小值】，下拨是【大值】—— 和直觉相反
 *    位置模式 = 上拨 = 小值
 *    速度模式 = 下拨 = 大值 */
#define CTRL_SWA_POS_MAX         500U   /* CH5 <  500 → 位置模式（上拨）*/
#define CTRL_SWA_SPEED_MIN      1500U   /* CH5 > 1500 → 速度模式（下拨）*/
/* 中间那段 → 停机 */

/* ---- 目标范围 ---- */
#define CTRL_ANGLE_LIMIT_DEG     90.0f  /* 位置模式：摇杆推到底 = ±90° */

/* ⚠️ 速度模式：额定转速的 1/2
 *    依据：C620 手册第 12 页"搭配 M3508 时的电机性能曲线"
 *          n（转速）轴范围 0~450 rpm，曲线水平段约 435 rpm（空载）
 *          → 435 ÷ 2 ≈ 217，这里取 215 留一点余量
 *    ⚠️ 这个数是从图上刻度估读的，上机时按手册再确认一次 */
#define CTRL_SPEED_LIMIT_RPM    215.0f

/* ---- 摇杆死区（防止摇杆回中不准导致电机慢慢爬）---- */
#define CTRL_STICK_DEADZONE       0.03f

/* ---- ⭐ 目标值斜坡限速（防止"目标突变 → 电机猛冲"）----
 * 位置模式：目标角度每秒最多变化 180°（0 到 90° 用 0.5 秒）
 *           ⚠️ 原来写 360（0.25 秒），推杆快的时候目标升太猛 → 冲过头
 *              → 降到 180 之后，不管推多快，目标都是平稳上升
 * 速度模式：目标转速每秒最多变化 600 rpm
 *
 * 为什么需要：拨档位的瞬间，目标值可能突变，位置环会看到巨大误差
 * → 全速冲过去。加斜坡后目标是"慢慢挪过去"的 */
#define CTRL_POS_SLEW_DEG_PER_S  180.0f
#define CTRL_SPD_SLEW_RPM_PER_S  600.0f

/* ---- 电流变化率限制（不让电流一步跳到底）----
 * 1000000/s：从 0 到满量程 16384 约需 16 ms
 *
 * 为什么需要：切档位的那一瞬间，速度环的目标会突然变（比如从 200rpm 变成 0），
 * 电流会跟着跳一下。加了这个限制之后变成一个 16ms 的爬升，冲击小很多。
 * 16 ms 相对整个响应过程（0.25 秒左右）很短，所以不会拖慢控制。 */
#define CTRL_CURRENT_SLEW_PER_S  1000000.0f


/* ============================================================================
 * 二、档位
 * ==========================================================================*/
typedef enum {
    CTRL_MODE_STOP  = 0,    /* 拨杆在中间 → 停机 */
    CTRL_MODE_POS,          /* 位置模式（SWA5 上拨）*/
    CTRL_MODE_SPEED         /* 速度模式（SWA5 下拨）*/
} CtrlMode_t;


/* ============================================================================
 * 三、对外函数
 * ==========================================================================*/

/* 初始化：初始化两路 PID + 复位内部状态
 * 在 main.c 的上电自测之后、启动接收之前调用一次 */
void Control_Init(void);

/* ⭐ remoteTask 调用（每 10 ms 一次）：读遥控 + 判档位 + 算目标 */
void Control_RemoteUpdate(void);

/* ⭐ controlTask 调用（每 1 ms 一次）：保护 + 串级 PID + 发 CAN */
void Control_Update(void);

/* 给 debug 模块读的接口（画曲线用）*/
float      Control_GetTargetDeg(void);      /* 位置环目标，单位 度 */
float      Control_GetTargetRpm(void);      /* 速度环目标，单位 输出轴 rpm */


/* ============================================================================
 * 四、自测（不用遥控器、不用电机就能验证映射和限速逻辑）
 * ==========================================================================*/
int Control_SelfTest(void);


#endif /* CONTROL_H */

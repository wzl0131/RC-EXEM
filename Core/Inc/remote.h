/* ============================================================================
 * remote.h  ——  SBUS 遥控接收模块（头文件）
 * ----------------------------------------------------------------------------
 * 接口（有什么）在这，实现代码在 remote.c
 *
 * 硬件链路：
 *   遥控器 →（2.4G）→ 接收机 →（SBUS 信号线）→ A 板 P8 口
 *          → 板载反相器 → USART1_RX (PB7)
 *
 * USART1 配置（CubeMX 里已配好）：
 *   100000 波特率 / 9 位字长(8 数据 + 1 偶校验) / 偶校验 / 2 停止位 / 只收
 *   → 这就是 SBUS 的格式（SBUS 的信号是反相的，A 板的 P8 口有反相器，所以不用管）
 * ==========================================================================*/

#ifndef REMOTE_H
#define REMOTE_H

#include <stdint.h>


/* ============================================================================
 * 一、SBUS 协议常量
 * ==========================================================================*/

#define SBUS_FRAME_LEN      25U      /* 一帧 25 个字节 */
#define SBUS_HEADER         0x0FU    /* 第 1 个字节必须是 0x0F */
#define SBUS_TAIL           0x00U    /* 第 25 个字节必须是 0x00 */
#define SBUS_CH_NUM         16U      /* 一帧里有 16 个通道 */

/* ---- 通道值范围 ----
 * ⚠️ 理论值（SBUS 协议）：172 ~ 1811，中位 992
 *    实测值（HT-10A 遥控器）：192 ~ 1792，中位 992
 *    → 这个遥控器的实际行程是 ±800，比理论值小一点
 *    → 必须用【实测值】归一化，摇杆推到底才能正好是 ±1.0（对应 ±90°）
 *    → 用理论值的话推到底只有 0.977，只能到 87.9°，到不了 90° */
#define SBUS_CH_MIN         192U     /* 实测最小（推到最下 / 最左）*/
#define SBUS_CH_MID         992U     /* 中位 */
#define SBUS_CH_MAX         1792U    /* 实测最大（推到最上 / 最右）*/

/* 通信超时：超过这么久没收到完整帧，就认为遥控器断连
 * SBUS 一般 7~14 ms 一帧，所以 50 ms 相当于"连续丢了好几帧" */
#define REMOTE_TIMEOUT_MS   50U


/* ============================================================================
 * 二、通道号 → 摇杆/拨杆 的对应关系（HT-10A 出厂默认）
 * ----------------------------------------------------------------------------
 * ⚠️ 遥控器里的通道映射【是可以改的】，所以下面是"默认值"不是"保证值"。
 *    上机时务必确认一次（10 分钟）：
 *      ① 把 remote.ch[0] ~ remote.ch[15] 加进 Keil 的 Watch 窗口
 *      ② 单独推某一个摇杆 / 拨一个开关
 *      ③ 看哪个通道的数字在变 → 那个通道就是它
 *      ④ 和下面比对，不一样就改下面的宏
 *
 * ⚠️ 说明书上的通道号是【从 1 开始】的，数组下标是【从 0 开始】的
 *          → CH5 对应 ch[4]
 * ==========================================================================*/

#define SBUS_CH1_RIGHT_LR   0U      /* 右摇杆 左右 */
#define SBUS_CH2_RIGHT_UD   1U      /* 右摇杆 上下（⚠️ 和 CH1 谁上下，上机确认）*/
#define SBUS_CH3_LEFT_UD    2U      /* 左摇杆 上下 */
#define SBUS_CH4_LEFT_LR    3U      /* 左摇杆 左右 */
#define SBUS_CH5_SWA        4U      /* ⭐ 左侧 SWA 三位开关（考核里的"SWA5"）*/
#define SBUS_CH6_SWB        5U      /* 左侧 SWB 开关 */
#define SBUS_CH7_SWC        6U      /* 右侧 SWC 开关 */
#define SBUS_CH8_SWD        7U      /* 右侧 SWD 开关 */
#define SBUS_CH9_VRA        8U      /* 旋钮 VRA */
#define SBUS_CH10_VRB       9U      /* 旋钮 VRB */


/* ============================================================================
 * 三、遥控数据结构体
 *   ⭐ 只存【事实】，不存"推导出来的状态"
 *      "在不在线"由 Remote_IsOnline() 现算，绝不存一个会过期的 online 字段
 * ==========================================================================*/
typedef struct {

    /* ---------- 第 1 组：通道原始值（172 ~ 1811）---------- */
    uint16_t ch[SBUS_CH_NUM];   /* ch[0] ~ ch[15] */

    /* ---------- 第 2 组：链路状态标志（来自第 24 个字节）---------- */
    uint8_t  failsafe;          /* 1 = 接收机进入了失控保护 */
    uint8_t  frame_lost;        /* 1 = 这一帧被标记为丢失 */

    /* ---------- 第 3 组：统计（判断在不在线、调试用）---------- */
    uint32_t last_rx_tick;      /* 最后一次收到【完整帧】的时刻（RTOS tick）*/
    uint32_t rx_count;          /* 一共收到了多少帧 */

} Remote_t;


/* ============================================================================
 * 四、全局变量声明（定义在 remote.c 里）
 * ==========================================================================*/
extern Remote_t remote;


/* ============================================================================
 * 五、对外函数声明
 * ==========================================================================*/

/* 初始化：把 remote 清零 + 把解析状态机复位（不启动硬件接收）*/
void Remote_Init(void);

/* 启动 USART1 的"单字节中断接收"（在 MX_USART1_UART_Init() 之后调用一次）*/
void Remote_StartReceive(void);

/* ⭐ 喂给它一个字节，它自己判断是不是帧头、自己攒满 25 个字节
 *   在 USART1 的中断回调里调用
 *   这样设计的好处：自测函数可以【逐个字节喂假数据】，完全不需要遥控器 */
void Remote_FeedByte(uint8_t b);

/* 现在遥控器在线吗？（现算：收到过帧 + 没失控 + 没超时）
 * 返回 1 = 在线，0 = 断连/失控 */
int  Remote_IsOnline(void);

/* 把一个通道的原始值(172~1811) 归一化成 -1.0 ~ +1.0
 *   992 → 0.0    1811 → +1.0    172 → -1.0
 * ⑦ 档位/摇杆映射会用它 */
float Remote_ChNorm(uint16_t raw);


/* ============================================================================
 * 六、自测函数（不需要遥控器就能验证解析对不对）
 *   返回 0 = 通过；返回非 0 = 第几项失败
 * ==========================================================================*/
int  Remote_SelfTest(void);


#endif /* REMOTE_H */      /* 头文件保护结束 */

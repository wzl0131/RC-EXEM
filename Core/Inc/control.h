/* ============================================================================
 * control.h  ——  控制逻辑模块（头文件）
 * ----------------------------------------------------------------------------
 * 这一层负责"决策"，不负责"怎么和硬件说话"：
 *
 *   remote  ──►  control  ──►  pid  ──►  can_motor
 *   (遥控值)     (档位/目标)    (算电流)    (发 CAN)
 *
 * 对应考核要求：
 *   ⑦ 档位切换 + 摇杆映射
 *       SWA5 上拨 → 位置模式（左摇杆 → 目标角度）
 *       SWA5 下拨 → 速度模式（右摇杆 → 目标转速）
 *       中间      → 停机
 *   ⑤ 位置环 + 速度环 串级 PID
 *       位置环：(目标角度, 实际角度) → 目标转速
 *       速度环：(目标转速, 实际转速) → 电流
 *   ⑨ 保护（最小版本）：遥控掉线 / 电调掉线 / 电调报错 → 立刻断电流
 * ==========================================================================*/

#ifndef CONTROL_H
#define CONTROL_H

#include <stdint.h>
#include "remote.h"      /* SBUS_CH5_SWA 等通道定义 */


/* ============================================================================
 * 一、可调参数
 * ==========================================================================*/

/* ---- 控制周期（必须和 controlTask 里的 osDelayUntil(1) 一致）---- */
#define CONTROL_DT_S            0.001f      /* 1 kHz → 1 ms */

/* ---- 哪个通道干什么（⚠️ 遥控器里映射可改，上机时推一下确认）---- */
#define CTRL_CH_POS_STICK       SBUS_CH3_LEFT_UD     /* 位置模式：左摇杆 上下 */
#define CTRL_CH_SPEED_STICK     SBUS_CH2_RIGHT_UD    /* 速度模式：右摇杆 上下 */

/* ---- SWA 三位开关的判档阈值（SBUS 值：172 / 992 / 1811）---- */
#define CTRL_SWA_POS_MIN        1500U   /* CH5 > 1500 → 位置模式（上拨）*/
#define CTRL_SWA_SPEED_MAX       500U   /* CH5 <  500 → 速度模式（下拨）*/
/* 500 ~ 1500 之间 → 停机（中位，也是最安全的位置）*/

/* ---- 目标值范围 ---- */
#define CTRL_ANGLE_LIMIT_DEG     90.0f  /* 位置模式：摇杆推到底 = ±90° */
#define CTRL_SPEED_LIMIT_RPM    235.0f  /* ⚠️ 速度模式：额定转速的 1/2
                                         *    手册曲线读出来额定约 469 rpm
                                         *    → 这里先按 235 写，上机核对后改 */

/* ---- 摇杆死区（防止摇杆回中不准导致电机慢慢爬）---- */
#define CTRL_STICK_DEADZONE       0.03f

/* ---- ⭐ 目标值斜坡限速（防止"目标突变 → 电机猛冲"）----
 * 位置模式：目标角度每秒最多变化 180°
 * 速度模式：目标转速每秒最多变化 600 rpm
 *
 * 为什么需要：拨档位的瞬间，目标值可能从"速度模式的 0 rpm"跳到
 * "位置模式的某个角度"，位置环会看到巨大的误差 → 全速冲过去。
 * 加了斜坡之后，目标是"慢慢挪过去"的 ✓ */
#define CTRL_POS_SLEW_DEG_PER_S  180.0f
#define CTRL_SPD_SLEW_RPM_PER_S  600.0f

/* ---- 电流变化率限制（保护电调和机械，不让电流一步跳到底）----
 * 200000/s 的含义：从 0 到满量程 16384 需要约 82 ms
 * ⚠️ 想关掉这个限制，就把它设得很大（比如 1.0e9f）*/
#define CTRL_CURRENT_SLEW_PER_S  200000.0f


/* ============================================================================
 * 二、档位枚举
 * ==========================================================================*/
typedef enum {
    CTRL_MODE_STOP  = 0,    /* 拨杆在中间 → 停机 */
    CTRL_MODE_POS,          /* 位置模式（SWA 上拨）*/
    CTRL_MODE_SPEED         /* 速度模式（SWA 下拨）*/
} CtrlMode_t;


/* ============================================================================
 * 三、对外函数声明
 * ==========================================================================*/

/* 初始化：初始化两路 PID + 清空内部状态
 * 在 controlTask 开头调用一次 */
void Control_Init(void);

/* ⭐ 控制循环主体：每 1 ms 调用一次
 * 里面依次做：安全检查 → 判档位 → 算目标 → 跑 PID → 发电流 */
void Control_Update(void);

/* 当前档位（调试/画曲线用）*/
CtrlMode_t Control_GetMode(void);

/* 当前的目标值（调试/画曲线用，考核要画的曲线就是它们）*/
float Control_GetTargetDeg(void);       /* 位置模式的目标角度，单位 度 */
float Control_GetTargetRpm(void);       /* 速度环的目标转速，单位 输出轴 rpm */


/* ============================================================================
 * 四、自测函数（不用遥控器、不用电机就能验证映射和限速逻辑）
 *   返回 0 = 通过；返回非 0 = 第几项失败
 * ==========================================================================*/
int Control_SelfTest(void);


#endif /* CONTROL_H */      /* 头文件保护结束 */

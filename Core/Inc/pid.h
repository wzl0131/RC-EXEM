/* ============================================================================
 * pid.h  ——  PID 控制器模块（头文件）
 * ----------------------------------------------------------------------------
 * 这个文件只写"接口"（对外提供什么类型、什么函数）
 * 具体的实现代码在 pid.c 里
 *
 * 用途（对应考核要求）：
 *   ④ 速度环：目标 rpm  → PID → 电流值              （SWA5 下档 = 纯速度模式）
 *   ⑤ 位置环：目标角度  → PID → 目标 rpm → 速度环    （SWA5 上档 = 位置模式，串级）
 * ==========================================================================*/

/* ---- 头文件保护：防止这个文件被重复包含 ---- */
#ifndef PID_H
#define PID_H

/* ---- 包含标准整数类型（uint8_t / int16_t ...）---- */
#include <stdint.h>


/* ============================================================================
 * 一、⭐ 单位约定（非常重要，搞错了 PID 永远调不出来）
 * ----------------------------------------------------------------------------
 *            输入 target      输入 actual      输出 output
 *  速度环    输出轴 rpm       输出轴 rpm       电流值（-16384 ~ 16384）
 *  位置环    输出轴 度        输出轴 度        目标 输出轴 rpm
 *
 * 说明：
 *   · 速度环的 actual 用 motor1.out_rpm（已经除过减速比，是【输出轴】的）
 *   · 位置环的 actual 用 motor1.out_angle_deg
 *   · 位置环的输出（目标 rpm）就是速度环的 target → 这就是"串级"
 * ==========================================================================*/


/* ============================================================================
 * 二、PID 参数默认值
 *   ⚠️ 这些只是"起步的猜测值"，必须上机慢慢整定，不要当成正确答案
 * ==========================================================================*/

/* ---- 速度环（内环）---- */
#define PID_SPEED_KP        30.0f      /* 比例 */
#define PID_SPEED_KI        0.5f       /* 积分 */
#define PID_SPEED_KD        0.0f       /* 微分（速度环一般不用 D）*/
#define PID_SPEED_OUT_MAX   16384.0f   /* 输出上限 = 电调电流最大值 */
#define PID_SPEED_I_MAX     8000.0f    /* 积分限幅（抗饱和）*/

/* ---- 位置环（外环）---- */
#define PID_ANGLE_KP        8.0f       /* 比例 */
#define PID_ANGLE_KI        0.0f       /* 积分（先不用，需要消除静差时再加）*/
#define PID_ANGLE_KD        0.3f       /* 微分 */
#define PID_ANGLE_OUT_MAX   300.0f     /* 输出上限 = 允许的最大【输出轴 rpm】*/
#define PID_ANGLE_I_MAX     50.0f      /* 积分限幅 */


/* ============================================================================
 * 三、PID 结构体
 *   一个 Pid_t 变量 = 一路完整的 PID 控制器（含参数 + 内部状态 + 本次结果）
 * ==========================================================================*/
typedef struct {

    /* ---------- 第 1 组：参数（上机整定这三个）---------- */
    float kp;               /* 比例系数：误差 × kp = 输出的一部分 */
    float ki;               /* 积分系数：消除稳态误差 */
    float kd;               /* 微分系数：抑制振荡、提前刹车 */

    /* ---------- 第 2 组：配置（限幅用，保护电机）---------- */
    float out_max;          /* 输出上限（输出下限自动取 -out_max）*/
    float i_max;            /* 积分累计的上下限（防止积分饱和 / wind-up）*/

    /* ---------- 第 3 组：内部状态（跨次调用要记住的东西）---------- */
    float integral;         /* 积分累计值：历次误差 × dt 的累加 */
    float last_actual;      /* 上一次的【测量值】（算微分用，见 pid.c 的说明）*/

    /* ---------- 第 4 组：本次计算结果（调试/画曲线用）---------- */
    float output;           /* 本次总输出 = p_out + i_out + d_out */
    float p_out;            /* P 项（单独存出来，方便看是哪一项在起作用）*/
    float i_out;            /* I 项 */
    float d_out;            /* D 项 */

} Pid_t;


/* ============================================================================
 * 四、全局变量声明
 *   extern = "变量在 pid.c 里【定义】了，这里只是声明"
 *   考核需要两路 PID，所以建两个变量
 * ==========================================================================*/
extern Pid_t pid_speed;     /* 速度环（内环）*/
extern Pid_t pid_angle;     /* 位置环（外环）*/


/* ============================================================================
 * 五、对外函数声明
 * ==========================================================================*/

/* 初始化：填入参数 + 把内部状态清零
 *   kp, ki, kd : 三个系数
 *   out_max    : 输出上限（下限自动 = -out_max）
 *   i_max      : 积分限幅
 * 例：Pid_Init(&pid_speed, PID_SPEED_KP, PID_SPEED_KI, PID_SPEED_KD,
 *              PID_SPEED_OUT_MAX, PID_SPEED_I_MAX);
 */
void  Pid_Init(Pid_t *p, float kp, float ki, float kd, float out_max, float i_max);

/* 清空积分和上一次的输出结果，但【保留】参数 和 上次测量值 last_actual
 *   ⚠️ 故意保留 last_actual：否则 D 项会算出巨大冲击（详见 pid.c 的说明）
 * 什么时候用：切换档位（SWA5 上下拨）时调用，避免残留的积分造成冲击 */
void  Pid_Reset(Pid_t *p);

/* 算一次 PID 输出，返回值 = 限幅后的输出
 *   target : 目标值（想要的）
 *   actual : 测量值（现在的）
 *   dt     : 距离上次调用过了多少【秒】（1 kHz 控制周期 → 传 0.001f）
 */
float Pid_Calc(Pid_t *p, float target, float actual, float dt);


/* ============================================================================
 * 六、自测函数（不需要电机就能验证 PID 数学对不对）
 *   返回 0 = 通过；返回非 0 = 第几项失败
 * ==========================================================================*/
int   Pid_SelfTest(void);


#endif /* PID_H */      /* 头文件保护结束 */

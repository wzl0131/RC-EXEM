/* ============================================================================
 * debug.h  ——  调试数据模块（头文件）
 * ----------------------------------------------------------------------------
 * 用途：只给 J-Scope 提供【考核要求画的那 5 条曲线】。
 *
 *   考核要求原文（验收标准）：
 *     "在 JScope 中实时显示目标角度、实际角度、目标转速、实际转速和 PID 输出曲线"
 *
 * ⭐ 为什么写成【扁平全局变量】而不是结构体：
 *     J-Scope 的 HSS 模式靠调试口直接读 RAM，只能看到符号表里有名字的变量。
 *     结构体成员有时选不到，扁平全局变量最保险。
 *
 * 在 J-Scope 的符号选择框里搜 "dbg_" 就能找到这 5 个。
 * ==========================================================================*/

#ifndef DEBUG_H
#define DEBUG_H

#include <stdint.h>


/* ============================================================================
 * 考核要画的 5 条曲线
 *   volatile：SEGGER 官方建议（保证尽快写进内存，不然可能被优化到寄存器里）
 * ==========================================================================*/
extern volatile float dbg_target_deg;    /* 目标角度（输出轴，度）  = 位置环输入 */
extern volatile float dbg_actual_deg;    /* 实际角度（输出轴，度）  = 位置环反馈 */
extern volatile float dbg_target_rpm;    /* 目标转速（输出轴 rpm）  = 速度环输入 */
extern volatile float dbg_actual_rpm;    /* 实际转速（输出轴 rpm）  = 速度环反馈 */
extern volatile float dbg_pid_out;       /* PID 输出（= 发给电调的电流值）*/


/* ============================================================================
 * 对外函数
 * ==========================================================================*/

/* 把这一周期的数据搬进上面 5 个变量（每 1 ms 调一次）
 * 在 freertos.c 的 controlTask 里、Control_Update() 之后调用 */
void Debug_Update(void);

/* 自测：造已知值验证搬运有没有出错，返回 0 = 通过 */
int  Debug_SelfTest(void);


#endif /* DEBUG_H */

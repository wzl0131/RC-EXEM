/* ============================================================================
 * protection.h  ——  保护逻辑模块（头文件）
 * ----------------------------------------------------------------------------
 * 职责：只负责"判断现在安不安全、最多允许给多大电流"，
 *       不负责发 CAN（发电流是 control.c 的事）
 *
 * 在 control.c 里的用法：
 *      limit = Protection_Update(mode);
 *      if (limit == 0)  →  断电流 + 复位 PID + 退出
 *      ... 跑 PID ...
 *      current = 再夹到 ±limit
 *
 * ⭐ 分两类故障：
 *    轻故障（遥控掉线 / 电调掉线）→ 条件消失就自动恢复
 *    重故障（电调报错 / 过温 / 角度越限 / 堵转）→ 【锁存】，
 *           必须把 SWA 拨回中间（停机档）才允许清除
 *
 *    为什么重故障要锁存？因为"过温"这种事，你松手它也不会自己好，
 *    如果自动恢复，电机就会反复冲击，越烧越热。
 * ==========================================================================*/

#ifndef PROTECTION_H
#define PROTECTION_H

#include <stdint.h>
#include "control.h"      /* CtrlMode_t */


/* ============================================================================
 * 一、阈值（上机时按实际情况调）
 * ==========================================================================*/

/* ---- 温度 ----
 * 手册：err_code 8 = 过温 ≥125℃，err_code 5 = ≥180℃
 * 我们在它报警之前先自己降额/停机，留一点余量 */
#define PROTECT_TEMP_DERATE_C       100.0f    /* 到这个温度开始线性降额 */
#define PROTECT_TEMP_STOP_C         115.0f    /* 到这个温度直接断电流 */

/* ---- 角度软限位 ----
 * 位置模式的目标范围是 ±CTRL_ANGLE_LIMIT_DEG(=±90°)
 * 实际角度超出"目标范围 + 这个余量"就认为失控 */
#define PROTECT_ANGLE_MARGIN_DEG      8.0f

/* ---- 堵转检测 ----
 * 条件（三个同时满足，且持续 PROTECT_STALL_MS）：
 *   ① 位置模式
 *   ② 上一周期发给电调的电流幅值 > PROTECT_STALL_CURRENT
 *   ③ 实际转速幅值 < PROTECT_STALL_RPM
 * 含义：拼命给电流但转不动 → 机构卡住了 */
#define PROTECT_STALL_CURRENT      8000.0f    /* 约 9.8 A */
#define PROTECT_STALL_RPM            15.0f    /* 输出轴 rpm */
#define PROTECT_STALL_MS            500U      /* 持续 500 ms（1 kHz → 500 个周期）*/


/* ============================================================================
 * 二、故障码
 * ==========================================================================*/
typedef enum {
    FAULT_NONE         = 0,     /* 正常 */
    FAULT_RC_OFFLINE   = 1,     /* 遥控掉线（轻故障）*/
    FAULT_ESC_OFFLINE  = 2,     /* 电调掉线，收不到 CAN 反馈（轻故障）*/
    FAULT_ESC_ERROR    = 3,     /* 电调报了错误码（重故障）*/
    FAULT_OVER_TEMP    = 4,     /* 电机过温（重故障）*/
    FAULT_ANGLE_LIMIT  = 5,     /* 超出角度软限位（重故障）*/
    FAULT_STALL        = 6      /* 堵转（重故障）*/
} FaultCode_t;


/* ============================================================================
 * 三、保护模块状态结构体
 * ==========================================================================*/
typedef struct {

    /* ---------- 第 1 组：当前状态 ---------- */
    FaultCode_t fault;          /* 当前故障码，FAULT_NONE = 正常 */
    uint8_t     over_temp;      /* 1 = 正在过温【降额】中（还没到停机温度）*/

    /* ---------- 第 2 组：限流结果 ---------- */
    float       limit;          /* 本次允许的电流幅值上限（0 = 必须断电流）*/
    float       temp;           /* 最近一次读到的温度，方便调试 */

    /* ---------- 第 3 组：诊断信息 ---------- */
    FaultCode_t last_fault;     /* 最近一次发生过的故障（不会被清零，用于点灯诊断）*/
    uint32_t    fault_ticks;    /* 累计处于故障状态多少个控制周期 */
    uint32_t    stall_ticks;    /* 堵转条件已持续多少个周期 */

} Protect_t;


/* ============================================================================
 * 四、全局变量声明（定义在 protection.c 里）
 * ==========================================================================*/
extern Protect_t protect;


/* ============================================================================
 * 五、对外函数声明
 * ==========================================================================*/

/* 初始化：清空状态 + 解除锁存 */
void Protection_Init(void);

/* ⭐ 每个控制周期调用一次（在 PID 之前）
 *   mode  : 当前档位
 *   返回  : 本次允许的电流幅值上限（0 = 必须断电流，直接 return）
 *
 * ⚠️ 返回 0 时必须【立刻】断电流，不能做斜坡缓降 —— 保护要的就是快 */
float Protection_Update(CtrlMode_t mode);


/* ============================================================================
 * 六、自测函数（不用电机、不用遥控器，靠改写全局变量来验证判断逻辑）
 *   返回 0 = 通过；返回非 0 = 第几项失败
 * ==========================================================================*/
int Protection_SelfTest(void);


#endif /* PROTECTION_H */      /* 头文件保护结束 */

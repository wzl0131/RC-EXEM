#ifndef CAN_MOTOR_H        
#define CAN_MOTOR_H       

#include <stdint.h>

/* ---- 发送帧（控制帧）的两个固定 ID ---- */
#define C620_TX_ID_1_4      0x200U   /* ID 1~4*/
#define C620_TX_ID_5_8      0x1FFU   /* ID 5~8*/

/* ---- 接收帧（反馈帧）的 ID 基准：实际 ID = 0x200 + 电调ID ---- */
#define C620_RX_ID_BASE     0x200U   /* 电调 ID=1 → 反馈 ID = 0x201 */

/* ---- 控制电流值的最大幅值（官方手册：-16384~0~16384 对应 -20~0~20A）---- */
#define C620_CURRENT_MAX    16384

/* ---- M3508 电机参数 ---- */
#define M3508_GEAR_RATIO    19.2032f /* 减速比 = 3591 / 187 ≈ 19.2032 */
#define M3508_CNT_PER_REV   8192.0f  /* 转子转一整圈 = 8192 个计数（13位编码器）*/

/* ---- 换算系数 ----
 * 反馈的角度是【转子】的（减速箱之前），我们要的是【输出轴】的（减速箱之后）
 *   输出轴角度 = 计数 × (360 / 8192 / 19.2032)
 * 整个表达式必须用括号包起来！否则宏替换后运算顺序会错
 */
#define CNT2DEG_OUT   (360.0f / M3508_CNT_PER_REV / M3508_GEAR_RATIO)  /* 计数 → 度 */
#define DEG2CNT_OUT   (1.0f / CNT2DEG_OUT)                             /* 度 → 计数 */
#define ROTOR_RPM2OUT_RPM   (1.0f / M3508_GEAR_RATIO)


/* ============================================================================
 * 二、电机状态结构体
 *   把一台电机的所有信息打包在一起，方便管理和传递
 * ==========================================================================*/
typedef struct {

    /* ---------- 第 1 组：原始反馈（直接从 CAN 帧里解析出来的）---------- */
    uint16_t raw_angle;         /* 转子机械角度，范围 0~8191（对应 0~360°）*/
    int16_t  raw_rpm;           /* 转子转速，单位 rpm（有正负，表示方向）*/
    int16_t  raw_current;       /* 实际转矩电流，范围 -16384~16384 */
    uint8_t  raw_temp;          /* 电机温度，单位 ℃ */
    uint8_t  err_code;          /* 电机错误码：0=无异常（手册第8字节）*/

    /* ---------- 第 2 组：多圈角度累计的内部状态 ---------- */
    int32_t  total_cnt;         /* 累计总计数（可正可负，能表示转很多圈）*/
    uint16_t last_raw_angle;    /* 上一次的原始角度（用来算增量）*/

    /* ---------- 第 3 组：换算后的物理量（给 PID 用）---------- */
    float    out_angle_deg;     /* 输出轴角度，单位 度 */
    float    out_rpm;           /* 输出轴转速，单位 rpm */

    /* ---------- 第 4 组：在线检测（判断电调有没有掉线）---------- */
    uint32_t last_rx_tick;      /* 最近一次收到反馈的时刻（单位：RTOS tick）*/
		uint8_t  inited;
    uint8_t  online;            /* 1 = 在线，0 = 掉线 */

} Motor3508_t;                  /* typedef：以后直接写 Motor3508_t 就能用 */


/* ============================================================================
 * 三、全局变量声明
 *   extern 的意思："这个变量在 can_motor.c 里【定义】了，这里只是【声明】"
 *   定义只能有 1 处，声明可以有无数处
 * ==========================================================================*/
extern Motor3508_t motor1;      /* 电机 ID = 1 的状态 */


/* ============================================================================
 * 四、对外函数声明（别的文件 #include 本头文件后就能调用这些）
 * ==========================================================================*/

/* 初始化：把电机状态全部清零 */
void M3508_Init(Motor3508_t *m);

/* 更新多圈累计角度（处理 8191→0 的过零问题）*/
void M3508_UpdateAngle(Motor3508_t *m, uint16_t raw);

/* 解析一帧反馈数据。返回 0 = 成功，-1 = 不是我们要的 ID */
int  C620_ParseRx(uint32_t std_id, const uint8_t *data);

/* 发送控制帧：给指定电调 ID 发送电流值 */
void C620_SendCurrent(uint8_t motor_id, int16_t current);
/* CAN 外设初始化：配滤波器 + 启动 CAN + 打开接收中断
 * 必须在 MX_CAN1_Init() 之后调用一次 */
void C620_CanInit(void);


/* ============================================================================
 * 五、自测函数（不需要电机、不需要遥控器就能验证代码对不对）
 *   返回 0 = 通过；返回非 0 = 失败，返回值指明是哪一项错了
 * ==========================================================================*/

/* 自测 1：验证 CAN 反馈帧的【大端解析】是否正确 */
int  C620_SelfTest(void);

/* 自测 2：验证【过零判断 + 多圈累计】是否正确 */
int  AngleAccumSelfTest(void);


#endif /* CAN_MOTOR_H */      /* 头文件保护结束 */

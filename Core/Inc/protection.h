/* ============================================================================
 * protection.h  ——  保护模块（头文件）
 * ----------------------------------------------------------------------------
 * 只做【通信 + 安全】的硬保护，不做任何"智能判断"。
 *
 *   ① 遥控器掉线      → 断电流
 *   ② 电调掉线        → 断电流
 *   ③ 电调报错误码    → 断电流
 *   ④ 电机过温 ≥115℃  → 断电流
 *
 * 这四条都是"真的出事了"才会触发，正常考核时碰不到。
 *
 * ⚠️ 为什么不加更多保护？
 *    曾经加过"角度软限位 / 堵转检测 / 过温降额 / 故障锁存"，结果：
 *      · 角度软限位（90°+8°=98°）→ 位置环去 90° 时一超调就锁存停机
 *      · 堵转检测 → 保持 90° 时转速≈0，会被误判成堵转停机
 *    → 正好和"保持 ±90°、不要过分抖动"这个要求冲突，所以全删了。
 *
 * ⭐ 原则：保护只在"必然出事"时动手，绝不在正常运行时插手。
 * ==========================================================================*/

#ifndef PROTECTION_H
#define PROTECTION_H

#include <stdint.h>


/* ============================================================================
 * 一、阈值
 * ==========================================================================*/

/* 电机过温停机（手册：电调自己到 125℃ 会报错误码 8，我们提前一点）*/
#define PROTECT_TEMP_STOP_C       115.0f


/* ============================================================================
 * 二、故障码
 * ==========================================================================*/
typedef enum {
    FAULT_NONE        = 0,      /* 正常 */
    FAULT_RC_OFFLINE  = 1,      /* 遥控器掉线 */
    FAULT_ESC_OFFLINE = 2,      /* 电调掉线（收不到 CAN 反馈）*/
    FAULT_ESC_ERROR   = 3,      /* 电调报了错误码 */
    FAULT_OVER_TEMP   = 4       /* 电机过温 */
} FaultCode_t;


/* ============================================================================
 * 三、全局变量
 *   当前故障码。FAULT_NONE = 正常。调试时可以直接加到 Watch 窗口看。
 * ==========================================================================*/
extern FaultCode_t protect_fault;


/* ============================================================================
 * 四、对外函数
 * ==========================================================================*/

/* 初始化：把故障码清成 FAULT_NONE（在 Control_Init 里调用）*/
void Protection_Init(void);

/* ⭐ 每个控制周期调用一次（1 kHz），返回本次允许的电流幅值上限
 *   返回 0     = 有故障，必须【立刻】断电流
 *   返回 16384 = 正常，不限制 */
float Protection_Update(void);


/* ============================================================================
 * 五、自测（靠改写全局变量构造场景，不需要硬件）
 * ==========================================================================*/
int Protection_SelfTest(void);


#endif /* PROTECTION_H */

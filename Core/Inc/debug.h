/* ============================================================================
 * debug.h  ——  调试数据模块（头文件）
 * ----------------------------------------------------------------------------
 * 用途：只给 J-Scope 提供【考核要求画的那 5 条曲线】。
 *
 *   考核要求原文（验收标准）：
 *     "在 JScope 中实时显示目标角度、实际角度、目标转速、实际转速和 PID 输出曲线"
 *
 * ⭐ 为什么写成【扁平全局变量】而不是结构体：
 *     J-Scope 的 HSS 模式靠调试口直接读 RAM，只能看到符号表里有名字的变量。
 *     结构体成员有时选不到，扁平全局变量最保险。
 *
 * 在 J-Scope 的符号选择框里搜 "dbg_" 就能找到这 5 个。
 * ==========================================================================*/

#ifndef DEBUG_H
#define DEBUG_H

#include <stdint.h>


/* ============================================================================
 * 考核要画的 5 条曲线
 *   volatile：SEGGER 官方建议（保证尽快写进内存，不然可能被优化到寄存器里）
 * ==========================================================================*/
extern volatile float dbg_target_deg;    /* 目标角度（输出轴，度）  = 位置环输入 */
extern volatile float dbg_actual_deg;    /* 实际角度（输出轴，度）  = 位置环反馈 */
extern volatile float dbg_target_rpm;    /* 目标转速（输出轴 rpm）  = 速度环输入 */
extern volatile float dbg_actual_rpm;    /* 实际转速（输出轴 rpm）  = 速度环反馈 */
extern volatile float dbg_pid_out;       /* PID 输出（= 发给电调的电流值）*/


/* ============================================================================
 * ⭐ 安全中心的状态（也搬出来给 J-Scope / Watch 看）
 * ----------------------------------------------------------------------------
 * 为什么需要这几个？
 *   安全中心内部的状态是 static 的，而且接口是【函数】——
 *   J-Scope 的 HSS 模式只能读 RAM 里的【全局变量】，读不了函数返回值。
 *   所以这里把关键状态搬到扁平全局变量。
 *
 * ⭐ 用法：J-Scope 里搜 "dbg_safety" 就能找到这 8 个，直接看数值
 *
 * ⚠️ 为什么不打包成一个数？
 *   之前我把"三个心跳"打包进一个 32 位变量、把"复位原因+次数"也打包了，
 *   省是省了，但 J-Scope 里显示十进制根本看不懂。
 *   现场要一眼能判断，所以拆成 8 个独立的变量 ✓
 * ==========================================================================*/

/* ---- 故障码（位掩码，可以同时有多个故障）---- */
extern volatile uint32_t dbg_safety_fault;          /* 当前故障码 */
extern volatile uint32_t dbg_safety_last_fault;     /* 上次复位【前】的故障码 */

/* ---- 崩溃记录 ---- */
extern volatile uint32_t dbg_safety_fault_pc;       /* 上次崩溃的地址（去 map 里查）*/

/* ---- 复位信息（拆开了，一眼能看懂）---- */
extern volatile uint32_t dbg_safety_reset_reason;   /* 复位原因：1=看门狗 2=软件 3=上电 4=引脚 */
extern volatile uint32_t dbg_safety_reset_count;    /* 复位次数 */

/* ---- 三个任务的心跳"年龄"（毫秒）
 *      正常都应该 < 20；超过 200 就说明那个任务卡死了 ---- */
extern volatile uint32_t dbg_safety_hb_ctrl;        /* 控制任务 controlTask  */
extern volatile uint32_t dbg_safety_hb_remote;      /* 遥控任务 remoteTask   */
extern volatile uint32_t dbg_safety_hb_debug;       /* 心跳任务 debugTask    */


/* ============================================================================
 * 对外函数
 * ==========================================================================*/

/* 把这一周期的数据搬进上面 5 个变量（每 1 ms 调一次）
 * 在 freertos.c 的 controlTask 里、Control_Update() 之后调用 */
void Debug_Update(void);

/* 自测：造已知值验证搬运有没有出错，返回 0 = 通过 */
int  Debug_SelfTest(void);


#endif /* DEBUG_H */

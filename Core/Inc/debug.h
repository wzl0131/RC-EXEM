/* ============================================================================
 * debug.h  ——  调试数据模块（头文件）
 * ----------------------------------------------------------------------------
 * 用途：把"考核要画曲线的那几个量"暴露成全局变量，
 *       然后用 SEGGER J-Scope 通过 J-Link 直接读内存画波形。
 *
 * ⭐⭐ 为什么用扁平全局变量：J-Scope 的 HSS 模式【不需要目标板写任何通信代码】，
 *     它靠调试口直接读 RAM。但它只能看到【符号表里有名字的变量】，
 *     结构体成员、static 变量有时不好选。
 *     → 所以考核要画的 5 条曲线做成扁平全局变量，最保险。
 *
 * 数据流：
 *   control.c 算完 → freertos.c 调 Debug_Update() → 写进这些变量
 *                                                     ↓ J-Link 直接读
 *                                                  J-Scope 画波形
 *
 * 注意：本模块不参与任何控制计算，整个删掉也不影响控制逻辑。
 * ==========================================================================*/

#ifndef DEBUG_H
#define DEBUG_H

#include <stdint.h>


/* ============================================================================
 * 一、⭐ 考核要画的 5 条曲线（扁平全局变量）
 * ----------------------------------------------------------------------------
 * 为什么加 volatile：
 *   SEGGER 官方建议"被采样的变量声明为 volatile，保证尽快写进内存"，
 *   否则编译器可能把它缓存在寄存器里，J-Scope 就读到旧值。
 *
 * 在 J-Scope 的符号选择框里直接搜这些名字：
 *   dbg_target_deg / dbg_actual_deg / dbg_target_rpm / dbg_actual_rpm / dbg_pid_out
 * ==========================================================================*/
extern volatile float dbg_target_deg;    /* 目标角度（输出轴，度）  ← 位置环输入 */
extern volatile float dbg_actual_deg;    /* 实际角度（输出轴，度）  ← 位置环反馈 */
extern volatile float dbg_target_rpm;    /* 目标转速（输出轴 rpm）  ← 速度环输入 */
extern volatile float dbg_actual_rpm;    /* 实际转速（输出轴 rpm）  ← 速度环反馈 */
extern volatile float dbg_pid_out;       /* PID 输出（= 发给电调的电流值）← 速度环输出 */


/* ============================================================================
 * 二、排查问题用的辅助量（打包成结构体，主要用 Keil 的 Watch 窗口看）
 * ==========================================================================*/
typedef struct {

    uint8_t  mode;          /* 当前档位：0=停机 1=位置 2=速度 */
    uint8_t  fault;         /* 故障码（protection.h 里的 FaultCode_t）*/
    uint8_t  over_temp;     /* 1 = 正在过温降额 */
    uint8_t  online_can;    /* 1 = 电调在线 */
    uint8_t  online_rc;     /* 1 = 遥控在线 */

    uint16_t raw_angle;     /* 收到的原始角度 0~8191（换算前）*/
    int16_t  raw_rpm;       /* 收到的转子 rpm（换算前）*/
    int16_t  raw_current;   /* 收到的实际转矩电流 */
    uint8_t  raw_temp;      /* 电机温度 ℃ */
    uint8_t  err_code;      /* 电调错误码 */

    /* ⚠️ 必须是 uint16_t！SBUS 通道值最大 1811，一个字节(255)装不下。
     *    上机时用它确认 SWA 三个档位到底是多少 */
    uint16_t swa;

    uint32_t tick;          /* 本周期时间戳（ms），可以当曲线的 X 轴 */

} Debug_t;

extern volatile Debug_t debug;


/* ============================================================================
 * 三、对外函数声明
 * ==========================================================================*/

/* 把当前这一周期的数据搬进上面的变量（每 1 ms 调一次）
 * 在 freertos.c 的 controlTask 里、Control_Update() 之后调用 */
void Debug_Update(void);

/* 自测：造几个已知值，验证"搬运"有没有出错
 *   返回 0 = 通过；返回非 0 = 第几项失败 */
int  Debug_SelfTest(void);


#endif /* DEBUG_H */      /* 头文件保护结束 */
